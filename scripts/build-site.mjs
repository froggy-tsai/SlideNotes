import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectDir = path.resolve(scriptDir, "..");
const siteDir = path.join(projectDir, "site");
const contentDir = path.join(projectDir, "content");
const distDir = path.join(projectDir, "dist");
const markerPath = path.join(distDir, ".slidenotes-generated");
const markerText = "Generated by SlideNotes scripts/build-site.mjs\n";

function ensureSafeRelativePath(value, label) {
  if (typeof value !== "string" || !value || path.isAbsolute(value)) {
    throw new Error(`${label} must be a non-empty relative path.`);
  }
  const resolved = path.resolve(projectDir, value);
  const relative = path.relative(projectDir, resolved);
  if (!relative || relative.startsWith(`..${path.sep}`) || relative === "..") {
    throw new Error(`${label} resolves outside the project: ${value}`);
  }
  return resolved;
}

async function copyPublishedPdf(sourceValue, outputRelative, label) {
  if (!sourceValue.toLowerCase().endsWith(".pdf")) {
    throw new Error(`${label} must point to a PDF: ${sourceValue}`);
  }
  const sourcePath = ensureSafeRelativePath(sourceValue, label);
  const sourceRelative = path.relative(contentDir, sourcePath);
  if (sourceRelative.startsWith(`..${path.sep}`) || sourceRelative === "..") {
    throw new Error(`${label} must be stored under content/: ${sourceValue}`);
  }
  const outputPath = path.join(distDir, outputRelative);
  await fs.access(sourcePath);
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.copyFile(sourcePath, outputPath);
  return `./${outputRelative.replaceAll(path.sep, "/")}`;
}

const catalogPath = path.join(contentDir, "published-catalog.json");
const catalog = JSON.parse(await fs.readFile(catalogPath, "utf8"));
if (catalog.schemaVersion !== 1 || !Array.isArray(catalog.courses)) {
  throw new Error("content/published-catalog.json has an unsupported schema.");
}

try {
  await fs.access(distDir);
  const marker = await fs.readFile(markerPath, "utf8").catch(() => "");
  if (marker !== markerText) {
    throw new Error("dist/ exists but is not marked as a SlideNotes build; refusing to replace it.");
  }
  await fs.rm(distDir, { recursive: true, force: true });
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}

await fs.cp(siteDir, distDir, { recursive: true });
const publicCourses = [];
const seenCourses = new Set();

for (const course of catalog.courses) {
  if (!course || typeof course.id !== "string" || typeof course.name !== "string" || !Array.isArray(course.decks)) {
    throw new Error("Each course needs an id, a name, and a decks array.");
  }
  if (seenCourses.has(course.id)) throw new Error(`Duplicate course id: ${course.id}`);
  seenCourses.add(course.id);

  const seenDecks = new Set();
  const decks = [];
  for (const deck of course.decks) {
    if (deck.status !== "published") {
      throw new Error(`Only explicitly published decks belong in the public catalog: ${course.id}/${deck.id}`);
    }
    if (typeof deck.id !== "string" || typeof deck.title !== "string") {
      throw new Error(`Decks require an id and title in ${course.id}.`);
    }
    if (seenDecks.has(deck.id)) throw new Error(`Duplicate deck id: ${course.id}/${deck.id}`);
    seenDecks.add(deck.id);

    const prefix = `materials/${course.id}/${deck.id}`;
    const originalPdf = await copyPublishedPdf(deck.originalPdf, `${prefix}/original.pdf`, "originalPdf");
    const translatedPdf = await copyPublishedPdf(deck.translatedPdf, `${prefix}/zh-TW.pdf`, "translatedPdf");
    decks.push({ id: deck.id, title: deck.title, originalPdf, translatedPdf });
  }
  publicCourses.push({ id: course.id, name: course.name, decks });
}

await fs.mkdir(path.join(distDir, "data"), { recursive: true });
await fs.writeFile(path.join(distDir, "data", "catalog.json"), `${JSON.stringify({ schemaVersion: 1, courses: publicCourses }, null, 2)}\n`, "utf8");
await fs.writeFile(markerPath, markerText, "utf8");
console.log(`Built SlideNotes to ${distDir} (${publicCourses.length} courses, ${publicCourses.reduce((sum, course) => sum + course.decks.length, 0)} published decks).`);
